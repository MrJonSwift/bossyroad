import type { WorldGenerator } from "./generator";

export type Direction = "forward" | "back" | "left" | "right";

export type RowKind = "grass" | "road" | "river" | "rail";

export type PropKind = "tree" | "rock" | "flower" | "bush";

export type RunPhase = "title" | "playing" | "dying" | "gameover";

/**
 * Why the run ended. The renderer uses this to pick the right reaction:
 * a squash for cars and trains, a splash for water, a lift for the eagle.
 */
export type DeathCause = "car" | "train" | "drown" | "eagle";

export type RailPhase = "warning" | "crossing" | "cooldown";

export interface Prop {
  kind: PropKind;
  x: number;
  variant?: number;
  length?: number;
}

/**
 * A generated coin on a row. River coins ride a log in the row's chain, so
 * their world position is derived from that log every step rather than baked
 * into a static row coordinate.
 */
export interface CoinSpec {
  /** Column for a coin on the row itself. */
  x: number;
  /** Chain index of the log this coin rides, when it is on water. */
  logIndex?: number;
  /** Offset from that log's centre, in tiles. */
  logOffset?: number;
}

/**
 * A generated traffic lane. One road row carries exactly one of these.
 * `gap` is free space between car boxes, not centre spacing; that keeps the
 * fairness rule independent of car size.
 */
export interface LaneSpec {
  dir: 1 | -1;
  /** Tiles per second. */
  speed: number;
  /** Free space between car boxes, in tiles. */
  gap: number;
  /** 0..1 offset of the traffic pattern around the wrap circle. */
  phase: number;
  /** Base car palette index; the lane walks through the palette. */
  variant: number;
}

/**
 * A river row's current and log chain. `lengths` tile a `LOG_CHAIN_WIDTH`
 * circle, so the chain is seamless and the player always has a log under them.
 */
export interface RiverSpec {
  dir: 1 | -1;
  /** Tiles per second. */
  speed: number;
  /** 0..1 offset of the chain around the wrap circle. */
  offset: number;
  /** Log lengths in chain order; the sum is LOG_CHAIN_WIDTH. */
  lengths: number[];
}

/**
 * A rail row's train timetable. Durations are generated once per row from the
 * single difficulty curve, so a row cannot change its warning half-way through.
 */
export interface RailSpec {
  dir: 1 | -1;
  /** Tiles per second while crossing. */
  speed: number;
  /** Train footprint along x, in tiles. */
  length: number;
  /** Seconds of warning before every crossing. */
  warnSeconds: number;
  /** Seconds of quiet after every crossing. */
  cooldownSeconds: number;
  /** 0..1 offset into the warning/crossing/cooldown cycle. */
  offset: number;
}

export interface WorldRow {
  z: number;
  kind: RowKind;
  variant: number;
  props: Prop[];
  /** Present on road rows generated by the endless world. */
  lane?: LaneSpec;
  /** Present on river rows generated by the endless world. */
  river?: RiverSpec;
  /** Present on rail rows generated by the endless world. */
  rail?: RailSpec;
  /** Deterministic pickups generated with the row. */
  coins?: CoinSpec[];
}

export interface CarState {
  /** Stable id so the renderer can reuse a mesh across frames. */
  id: number;
  /** Lane row. One road row is one lane. */
  z: number;
  /** Centre position in tile units. */
  x: number;
  dir: 1 | -1;
  /** Tiles per second. */
  speed: number;
  /** Footprint along x in tile units. */
  length: number;
  variant: number;
}

export interface LogState {
  /** Stable id (`z * 1000 + index`) so the renderer can reuse a mesh. */
  id: number;
  /** River row. */
  z: number;
  /** Centre position in tile units, wrapped to -LOG_WRAP..LOG_WRAP. */
  x: number;
  /** Previous fixed-step position, used to carry a rider by the delta. */
  prevX: number;
  dir: 1 | -1;
  /** Tiles per second. */
  speed: number;
  /** Footprint along x in tile units. */
  length: number;
}

export interface CoinState {
  /** Stable id (`z * 100 + index`) so the renderer can reuse a mesh. */
  id: number;
  /** Row the coin sits on. */
  z: number;
  /** Centre position in tile units. Log coins update this every step. */
  x: number;
  /** Collected coins stay in the list with `collected` set. */
  collected: boolean;
  /** Log the coin rides, or null for a coin on the row itself. */
  logId: number | null;
  /** Offset from that log's centre. */
  logOffset: number;
}

export interface RailState {
  /** One train per rail row, so the row depth is the id. */
  z: number;
  dir: 1 | -1;
  speed: number;
  length: number;
  warnSeconds: number;
  /** Time to cross the whole strip plus the train's own length. */
  crossSeconds: number;
  cooldownSeconds: number;
  /** Seconds into the current warning -> crossing -> cooldown cycle. */
  timer: number;
  phase: RailPhase;
  /** Train centre in tile units; only meaningful while crossing. */
  x: number;
  /** Previous fixed-step position, for the swept collision test. */
  prevX: number;
}

export interface PlayerState {
  x: number;
  z: number;
  fromX: number;
  fromZ: number;
  toX: number;
  toZ: number;
  hopT: number;
  hopping: boolean;
  facing: Direction;
  queued: Direction | null;
  /** Log the player is standing on, if any. */
  logId: number | null;
  /** Log whose motion is being carried through the current hop. */
  carrierLogId: number | null;
  /** Set when a log carried a hop target outside the nine-column strip. */
  offStrip: boolean;
}

export interface GameState {
  seed: number;
  /** Increments on every retry so the renderer can rebuild safely. */
  runId: number;
  phase: RunPhase;
  /** Seconds spent in the current phase. Drives death and retry timing. */
  phaseTime: number;
  /** Set when the run ends; reset on retry. */
  deathCause: DeathCause | null;
  player: PlayerState;
  cars: CarState[];
  logs: LogState[];
  rails: RailState[];
  /** Pickups in the live row window. Dropped with their row. */
  coinDrops: CoinState[];
  /** Player's coin balance. Persisted by the app layer. */
  coins: number;
  /** Coins collected in the current run, for the game-over card. */
  runCoins: number;
  /** Seconds since the last successful hop, or landing. Drives the eagle. */
  idleTime: number;
  score: number;
  best: number;
  /** Live window of rows, sorted by z. Recycled as the player advances. */
  world: WorldRow[];
  /** Generation cursor and RNG streams; belongs to the simulation. */
  generator: WorldGenerator;
  /** Backward player bound (the start line). */
  minZ: number;
  /** Furthest row the player may hop to, always ahead of the window. */
  maxZ: number;
}

export interface PlayerPose {
  x: number;
  z: number;
  y: number;
  hopT: number;
  facing: Direction;
  hopping: boolean;
}

export const PLAY_MIN_X = -4;
export const PLAY_MAX_X = 4;
